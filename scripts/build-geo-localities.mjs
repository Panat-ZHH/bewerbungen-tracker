#!/usr/bin/env node
// Builds lib/geo/localities-data.ts from the official Swiss localities directory
// ("Amtliches Ortschaftenverzeichnis mit Postleitzahl und Perimeter", swisstopo, open government data, free use with source attribution).
//
//   node scripts/build-geo-localities.mjs                 # downloads the current CSV (needs `unzip`)
//   node scripts/build-geo-localities.mjs path/to/AMTOVZ_CSV_LV95.csv
//
// The CSV has one row per (locality, PLZ, municipality) with LV95 coordinates. We keep one entry per (locality name, PLZ):
// the row with the largest share of addresses decides canton, municipality and coordinates. Output is a compact string table.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://data.geo.admin.ch/ch.swisstopo-vd.ortschaftenverzeichnis_plz/ortschaftenverzeichnis_plz/ortschaftenverzeichnis_plz_2056.csv.zip";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "lib", "geo", "localities-data.ts");

/** swisstopo approximate formulas LV95 (E, N) -> WGS84 (lat, lon), accuracy about 1 m. */
export function lv95ToWgs84(east, north) {
  const y = (east - 2600000) / 1e6;
  const x = (north - 1200000) / 1e6;
  const lon = 2.6779094 + 4.728982 * y + 0.791484 * y * x + 0.1306 * y * x * x - 0.0436 * y * y * y;
  const lat = 16.9023892 + 3.238272 * x - 0.270978 * y * y - 0.002528 * x * x - 0.0447 * y * y * x - 0.014 * x * x * x;
  return { lat: (lat * 100) / 36, lon: (lon * 100) / 36 };
}

async function readCsv(path) {
  if (path) return readFileSync(path, "utf8");
  const dir = mkdtempSync(join(tmpdir(), "wendapply-geo-"));
  try {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error(`Download failed: ${response.status}`);
    const zip = join(dir, "plz.zip");
    writeFileSync(zip, Buffer.from(await response.arrayBuffer()));
    execFileSync("unzip", ["-o", "-q", zip, "-d", dir]);
    const find = (folder) => readdirSync(folder, { withFileTypes: true }).flatMap((entry) => (entry.isDirectory() ? find(join(folder, entry.name)) : entry.name.endsWith(".csv") ? [join(folder, entry.name)] : []));
    const [csv] = find(dir);
    if (!csv) throw new Error("No CSV in the archive");
    return readFileSync(csv, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const csv = await readCsv(process.argv[2]);
const lines = csv.replace(/^﻿/, "").trim().split(/\r?\n/);
const header = lines.shift().split(";");
const col = (name) => { const index = header.indexOf(name); if (index < 0) throw new Error(`Missing column ${name}`); return index; };
const [cName, cPlz, cMunicipality, cBfs, cCanton, cShare, cE, cN] = ["Ortschaftsname", "PLZ4", "Gemeindename", "BFS-Nr", "Kantonskürzel", "Adressenanteil", "E", "N"].map(col);

const best = new Map();
const municipalities = new Map();
for (const line of lines) {
  const row = line.split(";");
  const share = Number.parseFloat(row[cShare]) || 0;
  const key = `${row[cName]}|${row[cPlz]}`;
  if (!best.has(key) || best.get(key).share < share) best.set(key, { row, share });
  municipalities.set(row[cBfs], row[cMunicipality]);
}
const clean = (value) => value.replace(/[;\n]/g, " ").trim();
const localities = [...best.values()].map(({ row }) => {
  const { lat, lon } = lv95ToWgs84(Number(row[cE]), Number(row[cN]));
  // rows without a canton are Liechtenstein
  return [clean(row[cName]), row[cPlz], row[cCanton] || "FL", lat.toFixed(4), lon.toFixed(4), row[cBfs]];
}).sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0], "de"));
const used = new Set(localities.map((entry) => entry[5]));
const municipalityRows = [...municipalities].filter(([bfs]) => used.has(bfs)).sort((a, b) => Number(a[0]) - Number(b[0])).map(([bfs, name]) => `${bfs};${clean(name)}`);

const out = `// GENERATED by scripts/build-geo-localities.mjs – do not edit by hand.
// Source: swisstopo, "Amtliches Ortschaftenverzeichnis mit Postleitzahl und Perimeter" (open data, free use with source attribution).
// ${SOURCE_URL}
// ${localities.length} localities (name;PLZ;canton;lat;lon;municipality number) and ${municipalityRows.length} municipalities (number;name).
export const LOCALITIES_GENERATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const LOCALITIES_RAW = ${JSON.stringify(localities.map((entry) => entry.join(";")).join("\n"))};
export const MUNICIPALITIES_RAW = ${JSON.stringify(municipalityRows.join("\n"))};
`;
writeFileSync(OUT, out);
console.log(`${localities.length} localities, ${municipalityRows.length} municipalities -> ${OUT} (${Math.round(out.length / 1024)} KB)`);
