/** Replaces `{key}` placeholders: fill("Schritt {n} von {total}", { n: 1, total: 3 }) -> "Schritt 1 von 3". Unknown keys become "". */
export const fill = (s: string, v: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k: string) => String(v[k] ?? ""));
